const pptxgen = require("pptxgenjs");
const { getProjectById } = require("../models/projectModel");
const { getPPTByProject } = require("../models/pptModel");
const pool = require("../config/database");

/**
 * Clean and sanitize project title for safe download filename.
 */
function sanitizeFilename(title) {
  const sanitized = String(title || "project")
    .toLowerCase()
    .replace(/[^a-z0-9_-]/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
  return sanitized || "project";
}

/**
 * Safely parse slide deck data from ppt_outputs records,
 * supporting both JSONB slides_json and legacy plain text string.
 */
function extractSlides(pptRecord, project) {
  if (!pptRecord) {
    return generateFallbackSlides(project);
  }

  // 1. Try structured slides_json if available
  if (pptRecord.slides_json) {
    const raw = pptRecord.slides_json;
    if (Array.isArray(raw)) return raw;
    if (raw && Array.isArray(raw.slides)) return raw.slides;
  }

  // 2. Try parsing ppt_text as JSON
  if (pptRecord.ppt_text) {
    try {
      const parsed = JSON.parse(pptRecord.ppt_text);
      if (Array.isArray(parsed)) return parsed;
      if (parsed && Array.isArray(parsed.slides)) return parsed.slides;
    } catch {
      // Plain text fallback
    }
  }

  // 3. Fallback for legacy plain-text
  return generateFallbackSlides(project, pptRecord.ppt_text);
}

function generateFallbackSlides(project, rawText = "") {
  return [
    {
      slideNumber: 1,
      title: project.title || "Project Presentation",
      subtitle: "HackFlow AI Pitch Deck",
      keyTakeaway: `Executive presentation for ${project.title}.`,
      bullets: [
        `Project: ${project.title}`,
        "Automated architecture and team orchestration",
        "Generated by HackFlow AI multi-agent pipeline"
      ],
      speakerNotes: `Good morning judges, we are excited to present ${project.title}.`
    },
    {
      slideNumber: 2,
      title: "Problem & Solution Overview",
      subtitle: "Addressing the Core Challenge",
      keyTakeaway: "Clear alignment between the market pain point and automated solution.",
      bullets: [
        `Problem Statement: ${project.problem_statement || "Manual project coordination overhead"}`,
        "Direct architectural resolution using autonomous agents",
        rawText ? rawText.slice(0, 150) : "End-to-end milestone breakdown"
      ],
      speakerNotes: "As shown on this slide, we targeted the primary friction point directly."
    }
  ];
}

/**
 * Builds a widescreen (16:9) presentation buffer using pptxgenjs.
 * Implements a cohesive modern theme with header accents, styled cards, callouts, and presenter notes.
 */
async function buildPptxBuffer(project, slides) {
  const pres = new pptxgen();

  // Widescreen 16:9
  pres.layout = "LAYOUT_16x9";
  pres.author = "HackFlow AI";
  pres.company = "HackFlow AI Platform";
  pres.title = `${project.title} - Pitch Deck`;

  // Color Palette Constants
  const THEME = {
    darkBg: "0F172A",      // Slate 900
    primaryAccent: "4F46E5",// Indigo 600
    secondaryAccent: "2563EB", // Blue 600
    lightBg: "F8FAFC",     // Slate 50
    cardBg: "FFFFFF",
    textDark: "1E293B",    // Slate 800
    textMuted: "64748B",   // Slate 500
    highlightBg: "EEF2FF", // Indigo 50
    highlightBorder: "C7D2FE", // Indigo 200
    accentCyan: "06B6D4"
  };

  slides.forEach((s, idx) => {
    const slide = pres.addSlide();
    const isTitleSlide = s.slideNumber === 1 || idx === 0;

    if (isTitleSlide) {
      // --- SLIDE 1: HERO TITLE SLIDE ---
      slide.background = { color: THEME.darkBg };

      // Decorative top accent bar
      slide.addShape(pres.ShapeType.rect, {
        x: 0,
        y: 0,
        w: "100%",
        h: 0.15,
        fill: { color: THEME.primaryAccent }
      });

      // Product Badge
      slide.addText("HACKFLOW AI • AUTOMATED PITCH DECK", {
        x: 0.8,
        y: 1.2,
        w: 8.0,
        h: 0.4,
        fontSize: 11,
        fontFace: "Arial",
        bold: true,
        color: THEME.accentCyan,
        charSpacing: 3
      });

      // Main Project Title
      slide.addText(s.title || project.title, {
        x: 0.8,
        y: 1.7,
        w: 11.5,
        h: 1.8,
        fontSize: 38,
        fontFace: "Arial",
        bold: true,
        color: "FFFFFF",
        valign: "middle"
      });

      // Subtitle / Tagline
      if (s.subtitle) {
        slide.addText(s.subtitle, {
          x: 0.8,
          y: 3.5,
          w: 11.5,
          h: 0.7,
          fontSize: 18,
          fontFace: "Arial",
          color: "94A3B8"
        });
      }

      // Key Takeaway Card on Title Slide
      if (s.keyTakeaway) {
        slide.addShape(pres.ShapeType.roundRect, {
          x: 0.8,
          y: 4.4,
          w: 11.5,
          h: 1.2,
          rectRadius: 0.1,
          fill: { color: "1E293B" },
          line: { color: THEME.primaryAccent, width: 1.5 }
        });

        slide.addText(`VISION: ${s.keyTakeaway}`, {
          x: 1.1,
          y: 4.5,
          w: 11.0,
          h: 1.0,
          fontSize: 14,
          fontFace: "Arial",
          color: "E2E8F0",
          italic: true
        });
      }

      // Footer metadata
      slide.addText(`Generated by HackFlow AI Autonomous Agents • ${new Date().toLocaleDateString()}`, {
        x: 0.8,
        y: 6.8,
        w: 10.0,
        h: 0.3,
        fontSize: 9,
        fontFace: "Arial",
        color: THEME.textMuted
      });

    } else {
      // --- CONTENT SLIDES (2 TO 7) ---
      slide.background = { color: THEME.lightBg };

      // Top Header Banner
      slide.addShape(pres.ShapeType.rect, {
        x: 0,
        y: 0,
        w: "100%",
        h: 1.25,
        fill: { color: THEME.darkBg }
      });

      // Slide Category / Number tag
      slide.addText(`SLIDE ${s.slideNumber || idx + 1} OF ${slides.length}`, {
        x: 0.8,
        y: 0.18,
        w: 4.0,
        h: 0.25,
        fontSize: 9,
        fontFace: "Arial",
        bold: true,
        color: THEME.accentCyan,
        charSpacing: 2
      });

      // Slide Title
      slide.addText(s.title || "Key Overview", {
        x: 0.8,
        y: 0.42,
        w: 10.5,
        h: 0.55,
        fontSize: 22,
        fontFace: "Arial",
        bold: true,
        color: "FFFFFF"
      });

      // Subtitle in Header
      if (s.subtitle) {
        slide.addText(s.subtitle, {
          x: 0.8,
          y: 0.95,
          w: 10.5,
          h: 0.25,
          fontSize: 11,
          fontFace: "Arial",
          color: "94A3B8"
        });
      }

      // Main Bullet Points Card
      slide.addShape(pres.ShapeType.roundRect, {
        x: 0.8,
        y: 1.55,
        w: 11.7,
        h: 3.6,
        rectRadius: 0.08,
        fill: { color: THEME.cardBg },
        line: { color: "E2E8F0", width: 1 }
      });

      const bulletsList = Array.isArray(s.bullets) && s.bullets.length > 0
        ? s.bullets
        : ["Core milestone implementation in progress", "Continuous validation across project modules"];

      const bulletObjects = bulletsList.map((b) => ({
        text: b,
        options: {
          fontSize: 14,
          fontFace: "Arial",
          color: THEME.textDark,
          bullet: { type: "bullet", code: "25AA" },
          breakLine: true,
          spaceBefore: 12,
          lineSpacingMultiple: 1.2
        }
      }));

      slide.addText(bulletObjects, {
        x: 1.1,
        y: 1.75,
        w: 11.1,
        h: 3.2,
        valign: "top"
      });

      // Key Takeaway Callout Box at bottom
      if (s.keyTakeaway) {
        slide.addShape(pres.ShapeType.roundRect, {
          x: 0.8,
          y: 5.35,
          w: 11.7,
          h: 1.2,
          rectRadius: 0.08,
          fill: { color: THEME.highlightBg },
          line: { color: THEME.highlightBorder, width: 1.5 }
        });

        slide.addText([
          {
            text: "KEY TAKEAWAY FOR JUDGES: ",
            options: { bold: true, color: THEME.primaryAccent, fontSize: 11 }
          },
          {
            text: s.keyTakeaway,
            options: { color: THEME.textDark, fontSize: 12, italic: true }
          }
        ], {
          x: 1.1,
          y: 5.45,
          w: 11.1,
          h: 1.0,
          valign: "middle"
        });
      }

      // Slide Footer
      slide.addText(`${project.title} • HackFlow AI`, {
        x: 0.8,
        y: 6.8,
        w: 6.0,
        h: 0.3,
        fontSize: 9,
        fontFace: "Arial",
        color: THEME.textMuted
      });

      slide.addText(`${idx + 1}`, {
        x: 11.5,
        y: 6.8,
        w: 1.0,
        h: 0.3,
        fontSize: 9,
        fontFace: "Arial",
        bold: true,
        align: "right",
        color: THEME.textMuted
      });
    }

    // Attach presenter speaker notes to every slide
    if (s.speakerNotes) {
      slide.addNotes(s.speakerNotes);
    }
  });

  return pres.write({ outputType: "nodebuffer" });
}

/**
 * Controller to handle GET /api/projects/:id/ppt/download
 */
async function downloadPptxHandler(req, res) {
  try {
    const projectId = req.params.id || req.params.projectId;
    const userId = req.user ? req.user.id : null;
    const userRole = req.user ? req.user.role : null;

    if (!projectId) {
      return res.status(400).json({ success: false, message: "Project ID is required." });
    }

    // 1. Verify project existence
    const project = await getProjectById(projectId);
    if (!project) {
      return res.status(404).json({ success: false, message: "Project not found." });
    }

    // 2. Access control verification: Creator or assigned team member
    if (userId) {
      const isCreator = project.created_by === userId;
      let isAssigned = false;

      if (!isCreator) {
        const taskCheck = await pool.query(
          "SELECT 1 FROM tasks WHERE project_id = $1 AND assigned_to = $2 LIMIT 1;",
          [projectId, userId]
        );
        isAssigned = taskCheck.rows.length > 0;
      }

      const roleUpper = String(userRole || "").toUpperCase();
      const isLeader = roleUpper === "TEAM_LEADER" || roleUpper === "LEADER";

      if (!isCreator && !isAssigned && !isLeader) {
        return res.status(403).json({ success: false, message: "Access forbidden: you do not have permission for this project." });
      }
    }

    // 3. Fetch latest PPT output
    const pptRecords = await getPPTByProject(projectId);
    const pptRecord = pptRecords && pptRecords.length > 0 ? pptRecords[0] : null;

    // 4. Extract structured slides
    const slides = extractSlides(pptRecord, project);

    // 5. Generate .pptx buffer
    const buffer = await buildPptxBuffer(project, slides);

    const safeFilename = `${sanitizeFilename(project.title)}-pitch-deck.pptx`;

    // 6. Return downloadable file buffer
    res.setHeader(
      "Content-Type",
      "application/vnd.openxmlformats-officedocument.presentationml.presentation"
    );
    res.setHeader("Content-Disposition", `attachment; filename="${safeFilename}"`);
    res.setHeader("Content-Length", buffer.length);

    return res.end(buffer);
  } catch (error) {
    console.error("Download PPTX Error:", error);
    return res.status(500).json({ success: false, message: "Failed to generate PPTX presentation." });
  }
}

module.exports = {
  sanitizeFilename,
  extractSlides,
  buildPptxBuffer,
  downloadPptxHandler
};
